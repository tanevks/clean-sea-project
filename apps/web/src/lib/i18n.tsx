type TranslationTree = (typeof translations)[WebLanguage];

type WebI18nContextValue = {
  language: WebLanguage;
  setLanguage: (language: WebLanguage) => void;
  t: TranslationTree;
};

const WebI18nContext = createContext<WebI18nContextValue | null>(null);

export function WebLanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<WebLanguage>("bg");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "bg" || stored === "en") {
      setLanguage(stored);
    }
  }, []);

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      t: translations[language]
    }),
    [language]
  );

  return (
    <WebI18nContext.Provider value={value}>{children}</WebI18nContext.Provider>
  );
}

export function useWebI18n() {
  const context = useContext(WebI18nContext);

  if (!context) {
    throw new Error("useWebI18n must be used within WebLanguageProvider.");
  }

  return context;
}



